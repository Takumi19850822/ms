DASHES = "\u2010\u2011\u2012\u2013\u2014\u2212"


def esc(value: str) -> str:
    return value.replace("'", "''")


def normalize_phone(value: str) -> str:
    for ch in DASHES:
        value = value.replace(ch, "-")
    return value.strip()


def parse_stores() -> list[tuple[str, str, str, str, str]]:
    rows: list[tuple[str, str, str, str, str]] = []
    seen_codes: set[str] = set()

    for line in STORES_TSV.strip().splitlines():
        parts = re.split(r"\t+", line.strip())
        if len(parts) != 4:
            raise ValueError(f"Invalid row: {line!r}")

        name, code, tel, fax = (part.strip() for part in parts)
        tel = normalize_phone(tel)
        fax = normalize_phone(fax)

        if code in seen_codes:
            raise ValueError(f"Duplicate store code: {code}")
        seen_codes.add(code)

        note = json.dumps({"tel": tel, "fax": fax}, ensure_ascii=False)
        rows.append((name, code, tel, fax, note))

    return rows


def main() -> None:
    rows = parse_stores()
    root = Path(__file__).resolve().parents[1]
    out_path = root / "seed_master_store.sql"

    lines = [
        "-- Store master seed for Supabase",
        "-- Run in Supabase SQL Editor (postgres role bypasses RLS)",
        "-- Mapping: code/storeId = store code, name = store name, note = JSON tel/fax",
        "",
        "DELETE FROM \"ResourceRecord\" WHERE \"resourceId\" = 'master-store';",
        "",
        "INSERT INTO \"ResourceRecord\" (",
        "  id,",
        "  \"resourceId\",",
        "  code,",
        "  name,",
        "  \"storeId\",",
        "  note,",
        "  \"updatedAt\",",
        "  version",
        ") VALUES",
    ]

    values = [
        "  (gen_random_uuid(), 'master-store', "
        f"'{esc(code)}', '{esc(name)}', '{esc(code)}', '{esc(note)}', now(), 1)"
        for name, code, _tel, _fax, note in rows
    ]
    lines.append(",\n".join(values))
    lines.append(";")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(rows)} stores to {out_path}")


if __name__ == "__main__":
    main()
